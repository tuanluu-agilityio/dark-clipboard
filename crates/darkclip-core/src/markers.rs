//! OS-independent privacy marker vocabulary (privacy-design §3).
//!
//! Adapters enumerate clipboard format names and map them to these markers with the pure
//! tables below; they never act on a marker (GC-04). The mandatory set is fixed in code and
//! is never configurable (GC-07, privacy-design §10).

/// A privacy marker found on the current clipboard offer.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum PrivacyMarker {
    /// The OS or the source app marked the content as concealed; `name` is the format name.
    OsConcealed { name: &'static str },
    /// Darkshot's full exclusion set (reported separately for statistics; same effect).
    DarkshotExcluded,
    /// "Do not sync" (Windows `CanUploadToCloudClipboard` = 0). Not a skip on its own.
    NoCloud,
    /// macOS `org.nspasteboard.TransientType`.
    Transient,
    /// macOS `org.nspasteboard.AutoGeneratedType`.
    AutoGenerated,
    /// Linux `x-kde-passwordManagerHint` = `secret`.
    PasswordManagerHint,
}

// Windows registered clipboard format names (privacy-design §3).
const WIN_EXCLUDE_MONITOR: &str = "ExcludeClipboardContentFromMonitorProcessing";
const WIN_HISTORY: &str = "CanIncludeInClipboardHistory";
const WIN_CLOUD: &str = "CanUploadToCloudClipboard";
const WIN_VIEWER_IGNORE: &str = "Clipboard Viewer Ignore";

// macOS pasteboard types (nspasteboard.org conventions).
const MAC_CONCEALED: &str = "org.nspasteboard.ConcealedType";
const MAC_TRANSIENT: &str = "org.nspasteboard.TransientType";
const MAC_AUTOGENERATED: &str = "org.nspasteboard.AutoGeneratedType";
/// 1Password legacy type; unverified, confirm in Phase 4.
const MAC_ONEPASSWORD: &str = "com.agilebits.onepassword";

// Linux MIME type (KDE Klipper / KeePassXC convention) and the value that conceals.
const LINUX_KDE_HINT: &str = "x-kde-passwordManagerHint";
const LINUX_KDE_SECRET: &[u8] = b"secret";

/// True for markers that always skip capture. Fixed in code; no setting changes it (GC-07).
pub fn is_mandatory(m: &PrivacyMarker) -> bool {
    match m {
        PrivacyMarker::OsConcealed { .. }
        | PrivacyMarker::DarkshotExcluded
        | PrivacyMarker::PasswordManagerHint => true,
        PrivacyMarker::NoCloud | PrivacyMarker::Transient | PrivacyMarker::AutoGenerated => false,
    }
}

fn push_unique(out: &mut Vec<PrivacyMarker>, m: PrivacyMarker) {
    if !out.contains(&m) {
        out.push(m);
    }
}

/// Windows mapping table, used by the Windows adapter.
/// Input: (registered format name, DWORD value if the data is exactly 4 bytes).
///
/// Registered format names are atoms, which Windows compares case-insensitively, so the
/// match is ASCII case-insensitive. A `CanIncludeInClipboardHistory` /
/// `CanUploadToCloudClipboard` value that is not a readable DWORD fails closed (treated as 0).
pub fn windows_markers(formats: &[(&str, Option<u32>)]) -> Vec<PrivacyMarker> {
    let mut out = Vec::new();
    let (mut exclude, mut history, mut cloud) = (false, false, false);
    for (name, value) in formats {
        if name.eq_ignore_ascii_case(WIN_EXCLUDE_MONITOR) {
            exclude = true;
            push_unique(
                &mut out,
                PrivacyMarker::OsConcealed {
                    name: WIN_EXCLUDE_MONITOR,
                },
            );
        } else if name.eq_ignore_ascii_case(WIN_HISTORY) {
            history = true;
            if value.unwrap_or(0) == 0 {
                push_unique(&mut out, PrivacyMarker::OsConcealed { name: WIN_HISTORY });
            }
        } else if name.eq_ignore_ascii_case(WIN_CLOUD) {
            cloud = true;
            if value.unwrap_or(0) == 0 {
                push_unique(&mut out, PrivacyMarker::NoCloud);
            }
        } else if name.eq_ignore_ascii_case(WIN_VIEWER_IGNORE) {
            push_unique(
                &mut out,
                PrivacyMarker::OsConcealed {
                    name: WIN_VIEWER_IGNORE,
                },
            );
        }
    }
    if exclude && history && cloud {
        push_unique(&mut out, PrivacyMarker::DarkshotExcluded);
    }
    out
}

/// macOS mapping table (pasteboard type identifiers). UTIs compare case-insensitively.
pub fn macos_markers(types: &[&str]) -> Vec<PrivacyMarker> {
    let mut out = Vec::new();
    for t in types {
        if t.eq_ignore_ascii_case(MAC_CONCEALED) {
            push_unique(
                &mut out,
                PrivacyMarker::OsConcealed {
                    name: MAC_CONCEALED,
                },
            );
        } else if t.eq_ignore_ascii_case(MAC_ONEPASSWORD) {
            push_unique(
                &mut out,
                PrivacyMarker::OsConcealed {
                    name: MAC_ONEPASSWORD,
                },
            );
        } else if t.eq_ignore_ascii_case(MAC_TRANSIENT) {
            push_unique(&mut out, PrivacyMarker::Transient);
        } else if t.eq_ignore_ascii_case(MAC_AUTOGENERATED) {
            push_unique(&mut out, PrivacyMarker::AutoGenerated);
        }
    }
    out
}

/// Linux mapping table (offered MIME types). The value is read by the adapter only for
/// `x-kde-passwordManagerHint`, and only up to 16 bytes.
///
/// The value `secret` (surrounding ASCII whitespace and NULs ignored) conceals; any other
/// readable value does not. A missing value (unreadable or over 16 bytes) fails closed.
pub fn linux_markers(mimes: &[(&str, Option<&[u8]>)]) -> Vec<PrivacyMarker> {
    let mut out = Vec::new();
    for (mime, value) in mimes {
        if !mime.eq_ignore_ascii_case(LINUX_KDE_HINT) {
            continue;
        }
        let secret = match value {
            None => true,
            Some(v) => trim_bytes(v) == LINUX_KDE_SECRET,
        };
        if secret {
            push_unique(&mut out, PrivacyMarker::PasswordManagerHint);
        }
    }
    out
}

fn trim_bytes(v: &[u8]) -> &[u8] {
    let pad = |b: &u8| b.is_ascii_whitespace() || *b == 0;
    let start = v.iter().position(|b| !pad(b)).unwrap_or(v.len());
    let end = v.iter().rposition(|b| !pad(b)).map_or(start, |i| i + 1);
    v.get(start..end).unwrap_or(&[])
}

#[cfg(test)]
mod tests {
    use super::*;

    fn darkshot_set() -> Vec<(&'static str, Option<u32>)> {
        vec![
            ("CF_UNICODETEXT", None),
            ("ExcludeClipboardContentFromMonitorProcessing", Some(0)),
            ("CanIncludeInClipboardHistory", Some(0)),
            ("CanUploadToCloudClipboard", Some(0)),
        ]
    }

    #[test]
    fn mandatory_set_is_fixed() {
        assert!(is_mandatory(&PrivacyMarker::OsConcealed { name: "x" }));
        assert!(is_mandatory(&PrivacyMarker::DarkshotExcluded));
        assert!(is_mandatory(&PrivacyMarker::PasswordManagerHint));
        assert!(!is_mandatory(&PrivacyMarker::NoCloud));
        assert!(!is_mandatory(&PrivacyMarker::Transient));
        assert!(!is_mandatory(&PrivacyMarker::AutoGenerated));
    }

    #[test]
    fn windows_darkshot_set_maps_to_darkshot_excluded() {
        let m = windows_markers(&darkshot_set());
        assert!(m.contains(&PrivacyMarker::DarkshotExcluded), "{m:?}");
    }

    #[test]
    fn windows_exclude_any_data_is_concealed() {
        for v in [None, Some(0), Some(1)] {
            let m = windows_markers(&[("ExcludeClipboardContentFromMonitorProcessing", v)]);
            assert!(m.iter().any(is_mandatory), "{v:?}: {m:?}");
            assert!(!m.contains(&PrivacyMarker::DarkshotExcluded));
        }
    }

    #[test]
    fn windows_history_values() {
        let zero = windows_markers(&[("CanIncludeInClipboardHistory", Some(0))]);
        assert!(matches!(
            zero.as_slice(),
            [PrivacyMarker::OsConcealed { .. }]
        ));
        let one = windows_markers(&[("CanIncludeInClipboardHistory", Some(1))]);
        assert!(one.is_empty(), "{one:?}");
        // Value not a 4-byte DWORD (or unreadable): fail closed.
        let unknown = windows_markers(&[("CanIncludeInClipboardHistory", None)]);
        assert!(matches!(
            unknown.as_slice(),
            [PrivacyMarker::OsConcealed { .. }]
        ));
    }

    #[test]
    fn windows_no_cloud_alone() {
        let m = windows_markers(&[
            ("CF_UNICODETEXT", None),
            ("CanUploadToCloudClipboard", Some(0)),
        ]);
        assert_eq!(m, vec![PrivacyMarker::NoCloud]);
        let one = windows_markers(&[("CanUploadToCloudClipboard", Some(1))]);
        assert!(one.is_empty());
    }

    #[test]
    fn windows_viewer_ignore_and_case() {
        let m = windows_markers(&[("Clipboard Viewer Ignore", None)]);
        assert!(matches!(m.as_slice(), [PrivacyMarker::OsConcealed { .. }]));
        // Registered format names are atoms, compared case-insensitively by Windows.
        let m = windows_markers(&[("excludeclipboardcontentfrommonitorprocessing", None)]);
        assert!(m.iter().any(is_mandatory));
    }

    #[test]
    fn windows_plain_formats_have_no_markers() {
        let m = windows_markers(&[
            ("CF_UNICODETEXT", None),
            ("HTML Format", None),
            ("PNG", None),
        ]);
        assert!(m.is_empty());
    }

    #[test]
    fn macos_table() {
        assert!(matches!(
            macos_markers(&["public.utf8-plain-text", "org.nspasteboard.ConcealedType"]).as_slice(),
            [PrivacyMarker::OsConcealed { .. }]
        ));
        assert!(matches!(
            macos_markers(&["com.agilebits.onepassword"]).as_slice(),
            [PrivacyMarker::OsConcealed { .. }]
        ));
        assert_eq!(
            macos_markers(&["org.nspasteboard.TransientType"]),
            vec![PrivacyMarker::Transient]
        );
        assert_eq!(
            macos_markers(&["org.nspasteboard.AutoGeneratedType"]),
            vec![PrivacyMarker::AutoGenerated]
        );
        assert!(macos_markers(&["public.utf8-plain-text", "public.png"]).is_empty());
    }

    #[test]
    fn linux_table() {
        let secret: &[u8] = b"secret";
        let accept: &[u8] = b"accept";
        assert_eq!(
            linux_markers(&[
                ("text/plain;charset=utf-8", None),
                ("x-kde-passwordManagerHint", Some(secret))
            ]),
            vec![PrivacyMarker::PasswordManagerHint]
        );
        assert!(linux_markers(&[("x-kde-passwordManagerHint", Some(accept))]).is_empty());
        assert!(linux_markers(&[("text/plain", None), ("image/png", None)]).is_empty());
    }

    #[test]
    fn linux_unreadable_hint_fails_closed() {
        // The adapter could not read the value (too large or read error): treat as secret.
        assert_eq!(
            linux_markers(&[("x-kde-passwordManagerHint", None)]),
            vec![PrivacyMarker::PasswordManagerHint]
        );
        let padded: &[u8] = b"secret\n";
        assert_eq!(
            linux_markers(&[("x-kde-passwordManagerHint", Some(padded))]),
            vec![PrivacyMarker::PasswordManagerHint]
        );
    }

    #[test]
    fn debug_shows_only_format_names() {
        let m = PrivacyMarker::OsConcealed {
            name: "Clipboard Viewer Ignore",
        };
        assert!(format!("{m:?}").contains("Clipboard Viewer Ignore"));
    }
}
